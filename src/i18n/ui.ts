export const ui: Record<Lang, Dict> = { en, nl, fr };
export type Key = keyof Dict;

export function useT(lang: Lang) {
  return (key: Key) => ui[lang][key];
}

/** Path for a page in a language: en has no prefix, others get /nl or /fr. */
export function localePath(lang: Lang, path = '/') {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return lang === 'en' ? clean : `/${lang}${clean === '/' ? '/' : clean}`;
}

/** getStaticPaths helper for [...lang] routes. */
export function langPaths() {
  return langs.map((lang) => ({ params: { lang: lang === 'en' ? undefined : lang }, props: { lang } }));
}
